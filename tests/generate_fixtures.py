"""Generate synthetic placeholder fixtures for metrics tests.

Ben will replace these with real photos (sharp Orion, blurry phone, daytime cat).
Run: python3 tests/generate_fixtures.py
"""

from __future__ import annotations

from pathlib import Path

import cv2
import numpy as np

FIX = Path(__file__).resolve().parent / "fixtures"


def _dark_sky(h: int = 480, w: int = 640, level: int = 12) -> np.ndarray:
    rng = np.random.default_rng(42)
    img = np.full((h, w), level, dtype=np.uint8)
    img = img + rng.integers(0, 4, size=img.shape, dtype=np.uint8)
    return np.clip(img, 0, 255).astype(np.uint8)


def _draw_stars(
    gray: np.ndarray,
    positions: list[tuple[int, int]],
    *,
    sigma: float = 1.2,
    peak: int = 240,
) -> np.ndarray:
    out = gray.astype(np.float32)
    yy, xx = np.mgrid[0 : gray.shape[0], 0 : gray.shape[1]]
    for x, y in positions:
        blob = peak * np.exp(-((xx - x) ** 2 + (yy - y) ** 2) / (2 * sigma**2))
        out = np.maximum(out, blob)
    return np.clip(out, 0, 255).astype(np.uint8)


def write_sharp_orion() -> None:
    """Dark field with many sharp star-like dots (≥15) — night sky."""
    gray = _dark_sky()
    # Pseudo-Orion belt + scattered field
    positions = [
        (220, 200),
        (260, 210),
        (300, 220),
        (200, 160),
        (320, 280),
        (180, 300),
        (400, 150),
        (450, 180),
        (120, 220),
        (500, 300),
        (350, 100),
        (100, 100),
        (550, 400),
        (80, 400),
        (420, 350),
        (160, 120),
        (480, 250),
        (300, 360),
        (240, 80),
        (380, 400),
    ]
    gray = _draw_stars(gray, positions, sigma=1.1, peak=245)
    bgr = cv2.cvtColor(gray, cv2.COLOR_GRAY2BGR)
    cv2.imwrite(str(FIX / "sharp_orion.jpg"), bgr, [int(cv2.IMWRITE_JPEG_QUALITY), 95])


def write_blurry_phone() -> None:
    """Same star field but Gaussian-blurred — lower sharpness than sharp_orion."""
    gray = _dark_sky()
    positions = [
        (220, 200),
        (260, 210),
        (300, 220),
        (200, 160),
        (320, 280),
        (180, 300),
        (400, 150),
        (450, 180),
        (120, 220),
        (500, 300),
        (350, 100),
        (100, 100),
        (550, 400),
        (80, 400),
        (420, 350),
        (160, 120),
        (480, 250),
        (300, 360),
        (240, 80),
        (380, 400),
    ]
    gray = _draw_stars(gray, positions, sigma=1.1, peak=245)
    gray = cv2.GaussianBlur(gray, (15, 15), 4.0)
    bgr = cv2.cvtColor(gray, cv2.COLOR_GRAY2BGR)
    cv2.imwrite(str(FIX / "blurry_phone.jpg"), bgr, [int(cv2.IMWRITE_JPEG_QUALITY), 85])


def write_daytime_cat() -> None:
    """Bright daytime-like frame with almost no star blobs → is_night_sky false."""
    rng = np.random.default_rng(7)
    h, w = 480, 640
    # Bright “daylight” base
    img = np.full((h, w, 3), 180, dtype=np.uint8)
    img[:, :] = (190, 175, 160)
    # Soft “cat” blob (not star-like)
    cv2.ellipse(img, (320, 260), (90, 70), 0, 0, 360, (120, 100, 80), -1)
    cv2.circle(img, (290, 240), 12, (40, 40, 40), -1)
    cv2.circle(img, (350, 240), 12, (40, 40, 40), -1)
    noise = rng.integers(-8, 8, size=img.shape, dtype=np.int16)
    img = np.clip(img.astype(np.int16) + noise, 0, 255).astype(np.uint8)
    cv2.imwrite(str(FIX / "daytime_cat.jpg"), img, [int(cv2.IMWRITE_JPEG_QUALITY), 90])


def main() -> None:
    FIX.mkdir(parents=True, exist_ok=True)
    write_sharp_orion()
    write_blurry_phone()
    write_daytime_cat()
    readme = FIX / "README.md"
    readme.write_text(
        "# Metrics fixtures (placeholders)\n\n"
        "These JPEGs are **synthetic placeholders** generated by "
        "`tests/generate_fixtures.py` so CI/unit tests can run before real "
        "night-sky photos are available.\n\n"
        "| File | Intent |\n"
        "|------|--------|\n"
        "| `sharp_orion.jpg` | Dark sky + sharp star dots |\n"
        "| `blurry_phone.jpg` | Same field, blurred (lower sharpness) |\n"
        "| `daytime_cat.jpg` | Bright non-sky → `is_night_sky` false |\n\n"
        "**Ben:** replace these with real captures when ready; keep the filenames.\n",
        encoding="utf-8",
    )
    print(f"Wrote fixtures → {FIX}")


if __name__ == "__main__":
    main()
