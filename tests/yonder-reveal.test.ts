/** Offline integration checks; no provider credentials or paid requests. */
import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { captureMeta, type CaptureDraft } from "../web/src/components/yonder/CaptureDetails";
import { toPhotoResult, revealObjects } from "../web/src/components/yonder/reveal-analysis";
import { identificationLabel } from "../web/src/components/yonder/analysis";
import { objectsFromResult } from "../web/src/components/yonder/photo-discoveries";
import { buildFovPrediction, crossCheckWithFov, findConstellationPattern, scoreSkyAnalysis, verifyAgainstStarDatabase, type SkyAnalysis } from "../lib/src/index";

const draft: CaptureDraft = { latitude: "37.87", longitude: "-122.27", takenAt: "2026-10-24T22:00", facing: "", elevation: "", fov: "", notes: "" };
const meta = captureMeta(draft)!;
assert.ok(meta);
assert.equal(meta.facingDegrees, undefined);
for (const invalid of [{ latitude: "" }, { longitude: "181" }, { takenAt: "invalid" }, { elevation: "91" }, { facing: "-1" }, { fov: "0" }]) assert.equal(captureMeta({ ...draft, ...invalid }), null);
const pattern = findConstellationPattern("Orion")!;
const stars = pattern.stars.map((star, index) => ({ id: `star-${index}`, name: star.name, x: star.x, y: star.y, brightness: 0.8 }));
const analysis: SkyAnalysis = { headline: "Orion · integration fixture", overview: "Synthetic catalog fixture for integration testing, not a live identification.", figures: [{ id: "orion", name: "Orion", kind: "constellation", confidence: 0.9, summary: "A catalog pattern", description: "Synthetic fixture", labelX: 0.5, labelY: 0.5, stars, lines: pattern.lines.flatMap((line) => { const from = stars.find((star) => star.name === line.from); const to = stars.find((star) => star.name === line.to); return from && to ? [{ from: from.id, to: to.id }] : []; }) }] };
const checked = verifyAgainstStarDatabase(analysis);
const prediction = buildFovPrediction(meta);
const reveal = { ...checked, score: scoreSkyAnalysis(checked.analysis, meta), prediction, fovCheck: crossCheckWithFov(checked.analysis, prediction), meta };
const result = toPhotoResult(reveal);
assert.equal(result.reveal, reveal, "Retain Ben's complete result without rewriting it");
assert.ok(checked.verification.acceptedStars.length > 0);
assert.equal(result.annotations, undefined, "Model catalog checks must not become plate-solved annotations");
assert.equal(result.final_score, reveal.score.finalScore);
assert.match(identificationLabel(result), /model estimate/);
assert.ok(objectsFromResult(result).some((object) => object.name === "Orion"));
const uiObjects = revealObjects(reveal);
assert.equal(uiObjects.length, 8, "Figma rings include the constellation and seven catalog-matched stars");
assert.ok(uiObjects.some((object) => object.name === "Betelgeuse" && object.x === 72 && object.y === 18));
assert.ok(uiObjects.every((object) => object.detail && object.figureId));
const restored = structuredClone(result);
assert.deepEqual(restored.reveal, reveal, "Full response and metadata survive memory serialization");
const empty: SkyAnalysis = { headline: "No objects", overview: "No reliable identification", figures: [] };
const emptyCheck = verifyAgainstStarDatabase(empty);
const emptyResult = toPhotoResult({ ...emptyCheck, score: scoreSkyAnalysis(empty, meta), prediction, fovCheck: crossCheckWithFov(empty, prediction), meta });
assert.equal(emptyResult.needs_review, true);
assert.equal(revealObjects(emptyResult.reveal!).length, 0, "Internal Nothing verified placeholder gets no Figma marker");
assert.equal(emptyResult.final_score, null);
assert.equal(objectsFromResult(emptyResult).length, 0);
assert.equal(identificationLabel(emptyResult), "No objects identified");
assert.equal(identificationLabel({ identity: { method: "plate-solved" } }), "Plate-solved", "Legacy Memories keep their identification status");
if (process.argv[2]) writeFileSync(process.argv[2], JSON.stringify(reveal));
console.log("Yonder integration passed: metadata validation, original Ben response preservation, real catalog/score pipeline, serialization, empty result, and legacy compatibility.");
